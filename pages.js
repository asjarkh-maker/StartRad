// «ИП» → «Индивидуальный предприниматель» и т. п.
function sellerTitle(S) {
  const st = String(S.seller.status || '').trim().toLowerCase();
  const name = need(S.seller.name, 'ФИО');
  if (st === 'ип' || st.includes('предприним')) return `Индивидуальный предприниматель ${name}`;
  if (st.includes('самозан')) return `${name}, плательщик налога на профессиональный доход (самозанятый)`;
  return `${need(S.seller.status, 'статус')} ${name}`;
}
